import { Fraunces, Inter } from "next/font/google";
import "./globals.css";
import type { Metadata } from "next";

import { SidebarProvider } from "@/components/ui/context/SidebarContext";
import { ThemeProvider } from "@/components/ui/context/ThemeContext";
import { AuthProvider } from "@/context/AuthContext";
import { ModalProvider } from "@/context/ModalContext";
import { AIAssistantProvider } from "@/context/AIAssistantContext";
import { ProductTourProvider } from "@/context/ProductTourContext";
import { GlobalCreateOpeningModal } from "@/components/modals/GlobalCreateOpeningModal";
import { AIAssistantDrawer } from "@/components/ai-assistant/AIAssistantDrawer";
import { ProductTour } from "@/components/product-tour/ProductTour";
import { Toaster } from "sonner";


// AskMiraa's pairing: Inter for the UI, Fraunces for page titles.
const outfit = Inter({ subsets: ["latin"], variable: "--font-inter" });
const fraunces = Fraunces({ subsets: ["latin"], variable: "--font-fraunces", axes: ["SOFT", "opsz"] });

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
  // Tell Google Translate / Chrome NOT to translate the app. Browser
  // translation rewrites React-managed text nodes, which then makes React's
  // own DOM updates throw "Failed to execute 'insertBefore' on 'Node'" and
  // crash the page (most visibly when a candidate enters the interview room).
  // The interview already handles language itself via the AI, so browser
  // translation of the React shell is both unwanted and unsafe.
  other: { google: "notranslate" },
};

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    // `translate="no"` is the W3C-standard signal browsers honor to skip
    // auto-translation — prevents the insertBefore crash described above.
    <html lang="en" translate="no" className={`${outfit.variable} ${fraunces.variable}`}>
      <body className={`${outfit.className} notranslate dark:bg-gray-900`}>
        <AuthProvider>
          <ThemeProvider>
            <SidebarProvider>
              <ModalProvider>
                <AIAssistantProvider>
                  <ProductTourProvider>
                    {children}
                    <Toaster richColors closeButton position="top-right" />
                    <GlobalCreateOpeningModal />
                    <AIAssistantDrawer />
                    <ProductTour />
                  </ProductTourProvider>
                </AIAssistantProvider>
              </ModalProvider>
            </SidebarProvider>
          </ThemeProvider>
        </AuthProvider>
      </body>
    </html>
  );
}
